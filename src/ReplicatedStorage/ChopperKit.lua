--[[ Unpack(imported, destination?) -> { [asset] = Model }
     Groups the imported parts ("MagmaseamAxe_Head", "MagmaseamAxe_Socket_Tip")
     into one Model per chopper. ]]
function ChopperKit.Unpack(imported: Instance, destination: Instance?)
	destination = destination or imported.Parent
	local assets = builtAssets()
	local models = {}
	for _, d in imported:GetDescendants() do
		if d:IsA("BasePart") then
			local name = baseName(d)
			for _, asset in assets do
				if string.sub(name, 1, #asset + 1) == asset .. "_" then
					local model = models[asset]
					if not model then
						model = Instance.new("Model")
						model.Name = asset
						model.Parent = destination
						models[asset] = model
					end
					d.Parent = model
					break
				end
			end
		end
	end
	local leftover = 0
	for _, d in imported:GetDescendants() do
		if d:IsA("BasePart") then
			leftover += 1
		end
	end
	if leftover == 0 then
		imported:Destroy()
	end
	return models
end

local function addAura(tool: Tool, info, emitFrom: BasePart)
	local fx = ChopperKit.TIER_FX[info.Tier]
	if not fx then
		return
	end
	local id = texture(fx.Texture)
	if id then
		local e = Instance.new("ParticleEmitter")
		e.Name = "ChopperAura"
		e.Texture = id
		e.Rate = fx.Rate
		e.Lifetime = NumberRange.new(0.6, 1.2)
		e.Speed = NumberRange.new(0.1, 0.4)
		e.SpreadAngle = Vector2.new(180, 180)
		e.Acceleration = Vector3.new(0, fx.Rise or 0.3, 0)
		e.Rotation = NumberRange.new(0, 360)
		e.RotSpeed = NumberRange.new(-60, 60)
		e.Size = NumberSequence.new({
			NumberSequenceKeypoint.new(0, 0),
			NumberSequenceKeypoint.new(0.3, 0.3),
			NumberSequenceKeypoint.new(1, 0),
		})
		e.LightEmission = 0.8
		e.LightInfluence = 0
		e.Color = ColorSequence.new(fx.Colors[1], fx.Colors[2])
		e.Shape = Enum.ParticleEmitterShape.Box
		e.Parent = emitFrom
	end
	if fx.Light then
		local glow = tool:FindFirstChild("Glow")
		local light = Instance.new("PointLight")
		light.Name = "ChopperLight"
		light.Color = fx.Light
		light.Brightness = 1.2
		light.Range = 8
		light.Shadows = false
		light.Parent = if glow and glow:IsA("BasePart") then glow else emitFrom
	end
end

--[[ MakeTool(model, asset?, parent?) -> Tool
     model: one unpacked chopper (parts <Asset>_Handle/_Head/_Glow/_Crystal and
     <Asset>_Socket_* markers). The Tool goes to `parent` (default
     ReplicatedStorage.Choppers), replacing an older one with the same name. ]]
function ChopperKit.MakeTool(model: Instance, assetName: string?, parent: Instance?): Tool
	local asset = assetName or model.Name
	local info = ChopperData.Choppers[asset]
	assert(info and info.Parts, "MakeTool: no ChopperData model entry for '" .. tostring(asset) .. "'")
	local socketPrefix = asset .. "_Socket_"

	local tool = Instance.new("Tool")
	tool.Name = info.DisplayName
	tool.CanBeDropped = false
	tool.RequiresHandle = true

	local parts, sockets = {}, {}
	for _, d in model:GetDescendants() do
		if d:IsA("BasePart") then
			local name = baseName(d)
			if string.sub(name, 1, #socketPrefix) == socketPrefix then
				sockets[string.sub(name, #socketPrefix + 1)] = d.Position
				d:Destroy()
			elseif info.Parts[name] then
				local entry = info.Parts[name]
				d.Name = entry.Role
				d.Anchored = false
				d.CanCollide = false
				d.CanQuery = false
				if entry.Look == "Neon" then
					d.Material = Enum.Material.Neon
					d.Color = Color3.fromHex(entry.Color)
				elseif entry.Look == "Glass" then
					d.Material = Enum.Material.Glass
					d.Color = Color3.fromHex(entry.Color)
					d.Transparency = 0.2
				end
				d.Parent = tool
				parts[entry.Role] = d
			end
		end
	end
	local handle = parts.Handle
	assert(handle, "MakeTool: no Handle part for " .. asset)
	local head = parts.Head or handle

	for role, part in parts do
		if role ~= "Handle" then
			part.Massless = true
			local weld = Instance.new("WeldConstraint")
			weld.Part0 = handle
			weld.Part1 = part
			weld.Parent = part
		end
	end

	for name, position in sockets do
		local a = Instance.new("Attachment")
		-- AnimationController puts the impact burst on TipAttachment.
		a.Name = if name == "Tip" then "TipAttachment" else name
		a.Parent = head
		a.WorldPosition = position
	end

	local top, bottom = head:FindFirstChild("TrailTop"), head:FindFirstChild("TrailBottom")
	if top and bottom then
		local colour = Color3.fromHex(info.TrailColor or "#FFFFFF")
		local trail = Instance.new("Trail")
		trail.Name = "SwingTrail" -- AnimationController switches it on during swings
		trail.Attachment0 = top :: Attachment
		trail.Attachment1 = bottom :: Attachment
		trail.Enabled = false
		trail.Lifetime = 0.18
		trail.FaceCamera = true
		trail.LightEmission = 0.6
		trail.Color = ColorSequence.new(Color3.new(1, 1, 1), colour)
		trail.Transparency = NumberSequence.new(0.3, 1)
		trail.Texture = texture("SwingStreak") or ""
		trail.Parent = head
	end
	addAura(tool, info, head)

	-- The hand holds the handle GripFromBottom studs up from its lowest point;
	-- the handle's long axis is Y.
	local length = handle.Size.Y
	tool.Grip = CFrame.new(0, -(length / 2 - (info.GripFromBottom or 1)), 0)
		* CFrame.Angles(0, math.rad(ChopperKit.GRIP_YAW_DEGREES), 0)

	tool:SetAttribute("Chopper", asset)
	tool:SetAttribute("WeaponType", info.WeaponType)
	tool:SetAttribute("Tier", info.Tier)
	tool:SetAttribute("StrengthPerClick", info.StrengthPerClick)
	tool:SetAttribute("Damage", info.StrengthPerClick)
	tool:SetAttribute("CashPrice", info.CashPrice)
	tool:SetAttribute("RobuxPrice", info.RobuxPrice)
	tool:SetAttribute("ShopOrder", info.Order)
	tool:SetAttribute("AttackSpeed", 1)

	local destination = parent or folder(ReplicatedStorage, "Choppers")
	local old = destination:FindFirstChild(tool.Name)
	if old then
		old:Destroy()
	end
	tool.Parent = destination
	if #model:GetChildren() == 0 then
		model:Destroy()
	end
	print(string.format("[ChopperKit] Made %s (%s %s, +%s per hit)", tool:GetFullName(), info.Tier, info.WeaponType,
		tostring(info.StrengthPerClick)))
	return tool
end

-- Is this imported model (any name) from Choppers.glb?
local function isChopperImport(model: Instance): boolean
	local assets = builtAssets()
	for _, d in model:GetDescendants() do
		if d:IsA("BasePart") then
			local name = baseName(d)
			for _, asset in assets do
				if string.sub(name, 1, #asset + 1) == asset .. "_" then
					return true
				end
			end
		end
	end
	return false
end

--[[ SetupAll() - the whole Studio setup in one call (command bar, Edit mode):
     finds the imported Choppers.glb in Workspace (whatever Studio named it),
     and makes every chopper in it a Tool in ReplicatedStorage.Choppers. ]]
function ChopperKit.SetupAll()
	local count = 0
	for _, child in workspace:GetChildren() do
		if child:IsA("Model") and isChopperImport(child) then
			for asset, model in ChopperKit.Unpack(child) do
				ChopperKit.MakeTool(model, asset)
				count += 1
			end
		end
	end
	print(string.format("[ChopperKit] SetupAll: %d choppers -> ReplicatedStorage.Choppers", count))
end

return ChopperKit

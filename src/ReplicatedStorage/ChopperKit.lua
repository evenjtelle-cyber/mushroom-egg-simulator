--[[
	ChopperKit  (ModuleScript)
	Location: ReplicatedStorage.ChopperKit

	Turns the choppers made by blender/GenerateChoppers.py into Tools, driven
	by ReplicatedStorage.ChopperData (generated by the same script). The
	starter Mossbark Hatchet comes from StarterSet.MakeTool instead.

	1) ONE-TIME SETUP in Studio (Edit mode, command bar). Import Choppers.glb
	   into Workspace, then:
	     require(game.ReplicatedStorage.ChopperKit).SetupAll()
	   Every chopper becomes a Tool in ReplicatedStorage.Choppers (named after
	   it, e.g. "Magmaseam Axe"), with its grip, swing trail, tier glow and
	   particles, and its stats as attributes (WeaponType, Tier,
	   StrengthPerClick, CashPrice, RobuxPrice, ShopOrder). AnimationController
	   plays the combo with any of them.

	2) IN YOUR GAME:
	     local list = K.ShopList()                  -- every chopper in shop order (incl. the starter)
	     local tool = K.GiveTool(player, "MagmaseamAxe")
]]

local ReplicatedStorage = game:GetService("ReplicatedStorage")

local ChopperData = require(ReplicatedStorage:WaitForChild("ChopperData"))
local VFXLibrary = require(ReplicatedStorage:WaitForChild("VFXLibrary"))

local ChopperKit = {}

-- Turn every chopper around its handle if blades face the wrong way in-hand
-- (try 180, then 90 / -90).
ChopperKit.GRIP_YAW_DEGREES = 0

-- Idle sparkle per tier (texture from VFXLibrary, colours, rate) and whether
-- the Glow part gets a light. Wood choppers stay plain.
ChopperKit.TIER_FX = {
	Wood = nil,
	Crystal = { Texture = "Sparkle", Colors = { Color3.fromRGB(240, 225, 255), Color3.fromRGB(180, 140, 255) }, Rate = 2 },
	Lava = { Texture = "Ember", Colors = { Color3.fromRGB(255, 220, 120), Color3.fromRGB(255, 90, 20) }, Rate = 4,
		Rise = 2, Light = Color3.fromRGB(255, 120, 40) },
	Void = { Texture = "VoidWisp", Colors = { Color3.fromRGB(220, 170, 255), Color3.fromRGB(110, 50, 200) }, Rate = 3,
		Light = Color3.fromRGB(190, 120, 255) },
	Celestial = { Texture = "FrostMote", Colors = { Color3.fromRGB(235, 250, 255), Color3.fromRGB(120, 230, 255) },
		Rate = 4, Rise = -0.5, Light = Color3.fromRGB(120, 235, 255) },
	Nebula = { Texture = "Sparkle", Colors = { Color3.fromRGB(255, 180, 235), Color3.fromRGB(95, 227, 255) }, Rate = 5,
		Light = Color3.fromRGB(255, 150, 230) },
	Solar = { Texture = "Ember", Colors = { Color3.fromRGB(255, 250, 200), Color3.fromRGB(255, 170, 40) }, Rate = 6,
		Rise = 2.5, Light = Color3.fromRGB(255, 210, 90) },
	Astral = { Texture = "Glint", Colors = { Color3.fromRGB(255, 246, 214), Color3.fromRGB(170, 150, 255) }, Rate = 6,
		Light = Color3.fromRGB(200, 185, 255) },
}

----------------------------------------------------------------------
-- Helpers
----------------------------------------------------------------------
local warned = {}
local function warnOnce(key: string, message: string)
	if not warned[key] then
		warned[key] = true
		warn("[ChopperKit] " .. message)
	end
end

local function texture(name: string): string?
	local id = VFXLibrary[name]
	local number = typeof(id) == "string" and tonumber(string.match(id, "%d+$"))
	if number and number > 0 then
		return id
	end
	warnOnce("tex-" .. name, "VFXLibrary." .. name .. " is not uploaded yet; effects using it are skipped.")
	return nil
end

local function baseName(instance: Instance): string
	return string.match(instance.Name, "^(.-)%.%d+$") or instance.Name
end

local function folder(parent: Instance, name: string): Instance
	local found = parent:FindFirstChild(name)
	if not found then
		found = Instance.new("Folder")
		found.Name = name
		found.Parent = parent
	end
	return found
end

-- Chopper asset names that have a model in Choppers.glb, longest first.
local function builtAssets(): { string }
	local list = {}
	for asset, info in ChopperData.Choppers do
		if info.Parts then
			table.insert(list, asset)
		end
	end
	table.sort(list, function(a, b)
		return #a > #b
	end)
	return list
end

----------------------------------------------------------------------
-- Shop data
----------------------------------------------------------------------
-- Every chopper in shop order: { { Asset = "MagmaseamAxe", DisplayName = ..., StrengthPerClick = ..., ... }, ... }
function ChopperKit.ShopList()
	local list = {}
	for asset, info in ChopperData.Choppers do
		local entry = table.clone(info)
		entry.Asset = asset
		table.insert(list, entry)
	end
	table.sort(list, function(a, b)
		return a.Order < b.Order
	end)
	return list
end

-- The Tool made by SetupAll for `asset` (or its display name), or nil.
function ChopperKit.GetTemplate(asset: string): Tool?
	local info = ChopperData.Choppers[asset]
	local choppers = ReplicatedStorage:FindFirstChild("Choppers")
	local found = choppers and choppers:FindFirstChild(if info then info.DisplayName else asset)
	return if found and found:IsA("Tool") then found else nil
end

-- Gives `player` a copy of a chopper Tool (in their Backpack). Server only.
function ChopperKit.GiveTool(player: Player, asset: string): Tool?
	local template = ChopperKit.GetTemplate(asset)
	if not template then
		warnOnce("missing-" .. asset, "No Tool for " .. asset .. " in ReplicatedStorage.Choppers; run SetupAll first.")
		return nil
	end
	local tool = template:Clone()
	tool.Parent = player:WaitForChild("Backpack")
	return tool
end


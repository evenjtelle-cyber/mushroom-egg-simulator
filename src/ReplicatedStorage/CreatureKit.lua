local function newHandle()
	local handle = { connections = {}, instances = {}, tweens = {}, alive = true }
	function handle.Stop()
		handle.alive = false
		for _, c in handle.connections do
			c:Disconnect()
		end
		for _, t in handle.tweens do
			t:Cancel()
		end
		for _, i in handle.instances do
			i:Destroy()
		end
		table.clear(handle.connections)
		table.clear(handle.tweens)
		table.clear(handle.instances)
	end
	return handle
end

local function track(handle, instance)
	if instance then
		table.insert(handle.instances, instance)
	end
	return instance
end

local PULSE = TweenInfo.new(1.6, Enum.EasingStyle.Sine, Enum.EasingDirection.InOut, -1, true)

local function pulse(handle, instance: Instance, goal)
	local tween = TweenService:Create(instance, PULSE, goal)
	table.insert(handle.tweens, tween)
	tween:Play()
end

-- Glow grows with rarity: Epic+ get a light, Legendary+ also a Highlight on
-- the Glow sub-model (Highlights are limited per client, so only the rarest).
local function addGlow(handle, model: Model, info, lightAt: Instance?)
	local detail = detailOf(info)
	local theme = themeOf(info)
	local glow = model:FindFirstChild("Glow")
	if glow and detail >= 4 then
		local highlight = track(handle, Instance.new("Highlight"))
		highlight.Adornee = glow
		highlight.DepthMode = Enum.HighlightDepthMode.Occluded
		highlight.FillColor = theme.Light
		highlight.FillTransparency = 0.8
		highlight.OutlineTransparency = 1
		highlight.Parent = model
		pulse(handle, highlight, { FillTransparency = 0.66 })
	end
	if lightAt and (detail >= 3 or glow) then
		local _, size = model:GetBoundingBox()
		local light = track(handle, Instance.new("PointLight"))
		light.Color = theme.Light
		light.Brightness = 0.6 + 0.25 * detail
		light.Range = math.clamp(size.Magnitude * 0.9, 8, 30)
		light.Shadows = false
		light.Parent = lightAt
		pulse(handle, light, { Brightness = light.Brightness * 1.35 })
	end
end

local function ambient(handle, parent: Instance?, info, rateScale: number)
	if not parent then
		return nil
	end
	local theme = themeOf(info)
	local detail = detailOf(info)
	local _, size = (parent:FindFirstAncestorWhichIsA("Model") :: Model):GetBoundingBox()
	local scale = math.clamp(size.Magnitude / 8, 0.6, 3)
	return track(handle, emitter(parent, theme.Ambient, {
		Rate = (0.6 + 0.9 * detail) * rateScale,
		Lifetime = NumberRange.new(1.4, 2.4),
		Speed = NumberRange.new(0.3 * scale, 0.9 * scale),
		SpreadAngle = Vector2.new(180, 180),
		Acceleration = Vector3.new(0, theme.Rise, 0),
		RotSpeed = NumberRange.new(-60, 60),
		Size = seq(0.3 * scale, 0),
		LightEmission = if theme.Ambient == "LeafBit" then 0 else 0.6,
		Color = ColorSequence.new(theme.Colors[1], theme.Colors[2]),
	}))
end

--[[ StartMonster(model) -> handle
     Idle from the data: Hop (a happy hop with a landing squash and dust),
     Hover (floats and sways), Breathe (slow rise and fall, looking around).
     Theme particles, light and glow scale with rarity. ]]
function CreatureKit.StartMonster(model: Model)
	local _, info = infoFor(model)
	local handle = newHandle()
	local root = model.PrimaryPart
	local detail = detailOf(info)
	local _, size = model:GetBoundingBox()

	ambient(handle, attachmentAt(model, "Back"), info, 1)
	addGlow(handle, model, info, attachmentAt(model, "Chest") or attachmentAt(model, "Back"))
	if detail >= 5 then
		-- Mythic and up: a second, slower layer of glints around the whole body.
		track(handle, root and emitter(root, "Glint", {
			Rate = 1.5,
			Lifetime = NumberRange.new(0.5, 0.9),
			Speed = NumberRange.new(0, 0),
			Size = NumberSequence.new({ NumberSequenceKeypoint.new(0, 0), NumberSequenceKeypoint.new(0.5, 0.6),
				NumberSequenceKeypoint.new(1, 0) }),
			Shape = Enum.ParticleEmitterShape.Box,
			LightEmission = 1,
			Color = ColorSequence.new(themeOf(info).Colors[1]),
		}))
	end

	local feet = attachmentAt(model, "Feet")
	local dust = info.Idle == "Hop" and feet and track(handle, emitter(feet, "DustPuff", {
		Enabled = false,
		Lifetime = NumberRange.new(0.4, 0.6),
		Speed = NumberRange.new(2, 3.5),
		SpreadAngle = Vector2.new(180, 5),
		Drag = 6,
		Size = seq(0.8, 1.6),
		Transparency = seq(0.3, 1),
		LightEmission = 0,
		Color = ColorSequence.new(Color3.fromRGB(200, 185, 150)),
	}))

	if root then
		local base = root.CFrame
		local height = size.Y
		local t = math.random() * 3 -- so a row of creatures doesn't move in sync
		local step
		if info.Idle == "Hop" then
			local every, hopTime, hopHeight = 2.4, 0.42, math.clamp(height * 0.25, 0.6, 2)
			step = function(dt)
				local phase = t % every
				local y, squash = 0, 0
				if phase < hopTime then
					local s = phase / hopTime
					y = hopHeight * 4 * s * (1 - s)
				elseif phase < hopTime + 0.18 then
					squash = math.sin((phase - hopTime) / 0.18 * math.pi)
				end
				if dust and phase >= hopTime and phase - dt < hopTime then
					dust:Emit(4)
				end
				return CFrame.new(0, y - squash * 0.12, 0) * CFrame.Angles(math.rad(-squash * 4), 0, 0)
			end
		elseif info.Idle == "Hover" then
			local amp = math.clamp(height * 0.06, 0.2, 0.8)
			step = function()
				return CFrame.new(0, amp + math.sin(t * 1.8) * amp, 0)
					* CFrame.Angles(math.rad(math.sin(t * 0.9) * 3), math.rad(math.sin(t * 0.5) * 8), math.rad(math.cos(t * 1.1) * 4))
			end
		else -- Breathe
			local amp = math.clamp(height * 0.012, 0.03, 0.25)
			step = function()
				local look = math.sin(t * 0.35) * math.sin(t * 0.13 + 1)
				return CFrame.new(0, (math.sin(t * 1.6) + 1) * amp, 0)
					* CFrame.Angles(math.rad(math.sin(t * 1.6) * 1.2), math.rad(look * 10), 0)
			end
		end
		table.insert(handle.connections, RunService.Heartbeat:Connect(function(dt)
			t += dt
			root.CFrame = base * step(dt)
		end))
		table.insert(handle.connections, {
			Disconnect = function()
				root.CFrame = base
			end,
		})
	end
	return handle
end

local function eggLabel(handle, model: Model, info, at: Instance, options)
	local attrs = info.Attributes
	local priceText = options.PriceText
	if priceText == nil and attrs.SellPrice then
		priceText = CreatureKit.FormatCash(attrs.SellPrice)
	end
	local gui = track(handle, Instance.new("BillboardGui"))
	gui.Name = "EggLabel"
	gui.Adornee = at
	gui.Size = UDim2.fromScale(6, if priceText then 2.8 else 2.1)
	gui.StudsOffsetWorldSpace = Vector3.new(0, 1.8, 0)
	gui.LightInfluence = 0
	gui.MaxDistance = 100

	local layout = Instance.new("UIListLayout")
	layout.HorizontalAlignment = Enum.HorizontalAlignment.Center
	layout.SortOrder = Enum.SortOrder.LayoutOrder
	layout.Parent = gui

	local function line(text: string, order: number, height: number, color: Color3)
		local label = Instance.new("TextLabel")
		label.LayoutOrder = order
		label.BackgroundTransparency = 1
		label.Size = UDim2.fromScale(1, height)
		label.Font = Enum.Font.FredokaOne
		label.TextScaled = true
		label.Text = text
		label.TextColor3 = color
		local stroke = Instance.new("UIStroke")
		stroke.Thickness = 2.5
		stroke.Color = Color3.fromRGB(30, 24, 16)
		stroke.Parent = label
		label.Parent = gui
		return label
	end

	line(attrs.EggName or info.DisplayName, 1, 0.5, WHITE)
	local rarity = line(info.Rarity, 2, 0.42, WHITE)
	local colors = CreatureKit.RARITY_COLORS[info.Rarity] or CreatureKit.RARITY_COLORS.Common
	local gradient = Instance.new("UIGradient")
	gradient.Rotation = 90
	gradient.Color = ColorSequence.new(colors[1], colors[2])
	gradient.Parent = rarity
	if detailOf(info) >= 4 then
		-- Legendary eggs: the gradient slowly sweeps.
		gradient.Rotation = 0
		gradient.Color = ColorSequence.new({
			ColorSequenceKeypoint.new(0, colors[2]),
			ColorSequenceKeypoint.new(0.5, colors[1]),
			ColorSequenceKeypoint.new(1, colors[2]),
		})
		local tween = TweenService:Create(gradient, TweenInfo.new(2.5, Enum.EasingStyle.Linear, Enum.EasingDirection.In, -1),
			{ Offset = Vector2.new(1, 0) })
		gradient.Offset = Vector2.new(-1, 0)
		table.insert(handle.tweens, tween)
		tween:Play()
	end
	if priceText then
		line(priceText, 3, 0.36, Color3.fromRGB(110, 230, 90))
	end
	gui.Parent = model
end

local eggHandles = setmetatable({}, { __mode = "k" })

--[[ StartEgg(model, options?) -> handle
     The egg sits on the ground and gives a little rock every few seconds,
     with theme particles (more with rarity), glow for the rare ones and the
     label. options = { PriceText = "$80" (default: its SellPrice), ShowLabel = true } ]]
function CreatureKit.StartEgg(model: Model, options)
	options = options or {}
	local _, info = infoFor(model)
	local handle = newHandle()
	local detail = detailOf(info)
	local core = model:FindFirstChild("EggCore", true)
	if core and core:IsA("BasePart") then
		local base = core.CFrame
		local t = math.random() * 3
		local every, duration = 3.2, 0.9
		local maxTilt = math.rad(6 + detail)
		table.insert(handle.connections, RunService.Heartbeat:Connect(function(dt)
			t += dt
			local phase = t % every
			local tilt = 0
			if phase < duration then
				local s = phase / duration
				tilt = math.sin(s * math.pi * 3) * (1 - s) * maxTilt
			end
			core.CFrame = base * CFrame.Angles(0, 0, tilt)
		end))
		handle.coreBase = base
	end
	local crown = attachmentAt(model, "Crown")
	local centre = attachmentAt(model, "EggCenter")
	ambient(handle, crown, info, 1.2)
	addGlow(handle, model, info, centre)
	if options.ShowLabel ~= false and (crown or core) then
		eggLabel(handle, model, info, (crown or core) :: Instance, options)
	end
	eggHandles[model] = handle
	return handle
end

-- Every visible egg part, with its assembled transparency (glass is 0.2).
local function shellParts(model: Model)
	local list = {}
	for _, d in model:GetDescendants() do
		if d:IsA("BasePart") and d.Name ~= "EggCore" then
			local original = d:GetAttribute("ShellTransparency")
			if original == nil then
				original = d.Transparency
				d:SetAttribute("ShellTransparency", original)
			end
			table.insert(list, { part = d, transparency = original })
		end
	end
	return list
end

--[[ PlayHatch(model, onReveal?) - a wobble that builds (longer and harder for
     rarer eggs), a flash, then the shell bursts into shards in the egg's own
     colours plus a theme burst. onReveal(centre) runs at the burst. Yields
     for about 2 s. Needs ReplicatedStorage.VFXMeshes.BestiaryVFXMeshes. ]]
function CreatureKit.PlayHatch(model: Model, onReveal: ((Vector3) -> ())?)
	local _, info = infoFor(model)
	local theme = themeOf(info)
	local detail = detailOf(info)
	local idle = eggHandles[model]
	local core = model:FindFirstChild("EggCore", true)
	if idle then
		idle.Stop()
		eggHandles[model] = nil
		if core and idle.coreBase then
			core.CFrame = idle.coreBase
		end
	end
	local middle = attachmentAt(model, "EggCenter")
	local centre = if middle then middle.WorldPosition
		elseif core then core.Position + Vector3.new(0, 2, 0)
		else model:GetPivot().Position

	if core and core:IsA("BasePart") then
		local base = core.CFrame
		local t, duration = 0, 1.0 + 0.1 * detail
		while t < duration do
			t += RunService.Heartbeat:Wait()
			local k = t / duration
			local amp = math.rad(3 + 12 * k * k)
			core.CFrame = base * CFrame.Angles(math.sin(t * (12 + 14 * k)) * amp, 0, math.cos(t * 10) * amp * 0.6)
		end
		core.CFrame = base
	end

	local flash = Instance.new("Highlight")
	flash.Adornee = model
	flash.FillColor = theme.Light:Lerp(WHITE, 0.6)
	flash.FillTransparency = 0.1
	flash.OutlineTransparency = 1
	flash.DepthMode = Enum.HighlightDepthMode.Occluded
	flash.Parent = model
	TweenService:Create(flash, TweenInfo.new(0.3), { FillTransparency = 1 }):Play()
	Debris:AddItem(flash, 0.35)

	-- Shard colours: the egg's own Plastic parts (biggest first is the root).
	local palette = {}
	for _, entry in info.Parts do
		if entry.Look == "Plastic" then
			table.insert(palette, Color3.fromHex(entry.Color))
		end
	end
	local rootEntry = info.Parts[info.Root]
	if rootEntry then
		table.insert(palette, 1, Color3.fromHex(rootEntry.Color))
		table.insert(palette, 1, Color3.fromHex(rootEntry.Color))
	end
	for _, entry in shellParts(model) do
		entry.part.Transparency = 1
	end

	local meshes = ReplicatedStorage:FindFirstChild("VFXMeshes")
	local set = meshes and meshes:FindFirstChild("BestiaryVFXMeshes")
	if set then
		local _, eggSize = model:GetBoundingBox()
		local spread = math.max(eggSize.X, eggSize.Z) * 0.45
		for _, template in set:GetDescendants() do
			if template:IsA("BasePart") and string.sub(template.Name, 1, 8) == "EggShard" then
				local shard = template:Clone()
				shard.Anchored = true
				shard.CanCollide = false
				shard.CanQuery = false
				shard.Color = palette[math.random(1, math.max(#palette, 1))] or WHITE
				shard.Material = Enum.Material.SmoothPlastic
				shard.CFrame = CFrame.new(centre + Vector3.new(math.random() - 0.5, math.random() - 0.3, math.random() - 0.5) * spread)
				shard.Parent = workspace
				local dir = Vector3.new(math.random() - 0.5, 0, math.random() - 0.5).Unit * math.random(3, 6)
				local spun = shard.CFrame * CFrame.Angles(math.random() * 6, math.random() * 6, math.random() * 6)
				TweenService:Create(shard, TweenInfo.new(0.3, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), {
					CFrame = spun + dir * 0.6 + Vector3.new(0, 2.2, 0),
				}):Play()
				task.delay(0.3, function()
					TweenService:Create(shard, TweenInfo.new(0.5, Enum.EasingStyle.Quad, Enum.EasingDirection.In), {
						CFrame = spun + dir + Vector3.new(0, -1.6, 0),
						Transparency = 1,
					}):Play()
				end)
				Debris:AddItem(shard, 0.9)
			end
		end
	else
		warnOnce("meshes", "ReplicatedStorage.VFXMeshes.BestiaryVFXMeshes not found; shard burst skipped.")
	end

	local burst = Instance.new("Attachment")
	burst.Position = centre
	burst.Parent = workspace.Terrain
	Debris:AddItem(burst, 3)
	local function fire(textureName: string, count: number, props)
		props.Enabled = false
		local e = emitter(burst, textureName, props)
		if e then
			e:Emit(count)
		end
	end
	fire(theme.Burst, 14 + 4 * detail, {
		Lifetime = NumberRange.new(0.8, 1.4),
		Speed = NumberRange.new(6, 11),
		SpreadAngle = Vector2.new(180, 180),
		Drag = 3,
		Acceleration = Vector3.new(0, -4 + theme.Rise, 0),
		RotSpeed = NumberRange.new(-200, 200),
		Size = seq(0.6, 0.2),
		LightEmission = if theme.Burst == "LeafBit" then 0 else 0.8,
		Color = ColorSequence.new(theme.Colors[1], theme.Colors[2]),
	})
	fire("DustPuff", 8, {
		Lifetime = NumberRange.new(0.5, 0.8),
		Speed = NumberRange.new(4, 7),
		SpreadAngle = Vector2.new(180, 20),
		Drag = 5,
		Size = seq(1.2, 2.6),
		Transparency = seq(0.2, 1),
		LightEmission = 0,
		Color = ColorSequence.new(Color3.fromRGB(210, 195, 160)),
	})
	if detail >= 3 then
		fire("ShockwaveRing", 1, {
			Lifetime = NumberRange.new(0.5, 0.5),
			Speed = NumberRange.new(0, 0),
			Size = seq(1, 10 + detail),
			Transparency = seq(0.2, 1),
			Orientation = Enum.ParticleOrientation.VelocityPerpendicular,
			EmissionDirection = Enum.NormalId.Top,
			LightEmission = 1,
			Color = ColorSequence.new(theme.Light),
		})
		fire("Sparkle", 10 + 3 * detail, {
			Lifetime = NumberRange.new(0.6, 1.2),
			Speed = NumberRange.new(3, 8),
			SpreadAngle = Vector2.new(180, 180),
			Drag = 2,
			Size = seq(0.6, 0),
			LightEmission = 1,
			Color = ColorSequence.new(WHITE, theme.Light),
		})
	end

	if onReveal then
		task.spawn(onReveal, centre)
	end
	task.wait(0.8)
end

-- Show the shell again after PlayHatch.
function CreatureKit.ResetEgg(model: Model)
	for _, entry in shellParts(model) do
		entry.part.Transparency = entry.transparency
	end
end

return CreatureKit

function CreatureKit.FollowerBonus(rarity: string)
	return CreatureKit.FOLLOWER_BONUS[rarity] or CreatureKit.FOLLOWER_BONUS.Common
end

-- Monster asset names of a family, most common first.
function CreatureKit.FamilyMonsters(family: string): { string }
	local list = {}
	for asset, info in BestiaryData.Assets do
		if info.Kind == "Monster" and info.Family == family then
			table.insert(list, asset)
		end
	end
	table.sort(list, function(a, b)
		return BestiaryData.Assets[a].Attributes.HatchChance > BestiaryData.Assets[b].Attributes.HatchChance
	end)
	return list
end

--[[ RollHatch(family, luck?) -> asset name. Uses each monster's HatchChance;
     luck (1 = none) multiplies the weight of everything except the most
     common monster, so luck shifts odds towards the rarer ones. ]]
function CreatureKit.RollHatch(family: string, luck: number?, rng: Random?): string?
	local list = CreatureKit.FamilyMonsters(family)
	if #list == 0 then
		return nil
	end
	luck = math.max(luck or 1, 0)
	local weights, total = {}, 0
	for i, asset in list do
		local w = BestiaryData.Assets[asset].Attributes.HatchChance * (if i == 1 then 1 else luck)
		weights[i] = w
		total += w
	end
	local roll = (rng or Random.new()):NextNumber() * total
	for i, w in weights do
		roll -= w
		if roll <= 0 then
			return list[i]
		end
	end
	return list[#list]
end

-- 25 -> "$25", 2500 -> "$2.5K", 6000000 -> "$6M", 7.8e9 -> "$7.8B"
function CreatureKit.FormatCash(value: number): string
	local units = { { 1e12, "T" }, { 1e9, "B" }, { 1e6, "M" }, { 1e3, "K" } }
	for _, u in units do
		if value >= u[1] then
			local text = string.format("%.1f", value / u[1]):gsub("%.0$", "")
			return "$" .. text .. u[2]
		end
	end
	return "$" .. tostring(math.floor(value))
end


--[[ Unpack(imported, destination?) -> { Model }
     Every part name starts with its asset ("LavaEgg_Basalt",
     "CinderpawPup_Socket_Back"). Parts are grouped into one Model per asset,
     parented to destination (default: where the import is). The emptied
     import is removed. ]]
function CreatureKit.Unpack(imported: Instance, destination: Instance?): { Model }
	destination = destination or imported.Parent
	-- Longest names first, so a short asset name never claims a longer one's parts.
	local assets = {}
	for asset in BestiaryData.Assets do
		table.insert(assets, asset)
	end
	table.sort(assets, function(a, b)
		return #a > #b
	end)

	local models, order = {}, {}
	for _, d in imported:GetDescendants() do
		if d:IsA("BasePart") then
			local name = baseName(d)
			for _, asset in assets do
				if string.sub(name, 1, #asset + 1) == asset .. "_" then
					local model = models[asset]
					if not model then
						model = Instance.new("Model")
						model.Name = asset
						model.Parent = destination
						models[asset] = model
						table.insert(order, model)
					end
					d.Parent = model
					break
				end
			end
		end
	end
	local leftover = 0
	for _, d in imported:GetDescendants() do
		if d:IsA("BasePart") then
			leftover += 1
		end
	end
	if leftover == 0 then
		imported:Destroy()
	else
		warnOnce("leftover", string.format("Unpack left %d unrecognised parts in %s", leftover, imported:GetFullName()))
	end
	print(string.format("[CreatureKit] Unpacked %d creatures", #order))
	return order
end

local function applyLook(part: BasePart, color: string?, look: string)
	if color then
		part.Color = Color3.fromHex(color)
	end
	for _, child in part:GetChildren() do
		if child:IsA("SurfaceAppearance") then
			child:Destroy()
		end
	end
	part.Transparency = 0
	part.Reflectance = 0
	if look == "Neon" then
		part.Material = Enum.Material.Neon
		return
	elseif look == "Glass" then
		part.Material = Enum.Material.Glass
		part.Transparency = 0.2
		return
	end
	part.Material = Enum.Material.SmoothPlastic
	if look ~= "Plastic" then
		return -- "Smooth": eyes and mouths stay clean, no studs
	end
	local studs = texture("StudOverlay")
	if not studs then
		return
	end
	local ok, err = pcall(function()
		local appearance = Instance.new("SurfaceAppearance")
		appearance.AlphaMode = Enum.AlphaMode.Overlay
		appearance.ColorMap = studs
		appearance.Parent = part
	end)
	if not ok then
		warnOnce("sa", "SurfaceAppearance needs Studio (command bar, Edit mode): " .. tostring(err))
	end
end

--[[ Assemble(model, asset?) - asset defaults to the model's name. Safe to
     run again on an assembled model. ]]
function CreatureKit.Assemble(model: Model, assetName: string?)
	local asset = assetName or model:GetAttribute("Asset") or model.Name
	local info = BestiaryData.Assets[asset]
	assert(info, "Assemble: no BestiaryData entry for '" .. tostring(asset) .. "'")
	local socketPrefix = asset .. "_Socket_"

	local parts, sockets = {}, {}
	for _, d in model:GetDescendants() do
		if d:IsA("BasePart") then
			local name = baseName(d)
			if string.sub(name, 1, #socketPrefix) == socketPrefix then
				table.insert(sockets, d)
			elseif d.Name ~= "EggCore" then
				table.insert(parts, d)
			end
		elseif d:IsA("WeldConstraint") and d.Name == "CreatureWeld" then
			d:Destroy()
		end
	end

	local root: BasePart? = nil
	for _, p in parts do
		if baseName(p) == info.Root then
			root = p
			break
		end
	end
	assert(root, "Assemble: no part named " .. tostring(info.Root) .. " in " .. model:GetFullName())

	local glow = model:FindFirstChild("Glow")
	if not (glow and glow:IsA("Model")) then
		glow = Instance.new("Model")
		glow.Name = "Glow"
		glow.Parent = model
	end

	local socketPositions = {}
	for _, s in sockets do
		socketPositions[string.sub(baseName(s), #socketPrefix + 1)] = s.Position
	end

	if info.Kind == "Egg" then
		-- Eggs sit on the ground. An invisible anchored core at the base centre
		-- is the root, so rocking and the hatch wobble pivot where it touches.
		local core = model:FindFirstChild("EggCore", true)
		if not (core and core:IsA("BasePart")) then
			core = Instance.new("Part")
			core.Name = "EggCore"
			core.Size = Vector3.new(0.5, 0.5, 0.5)
			core.Transparency = 1
			core.CanCollide = false
			core.CanQuery = false
			core.Parent = model
		end
		local _, size = model:GetBoundingBox()
		local base = socketPositions.Ground or (root.Position - Vector3.new(0, size.Y / 2, 0))
		core.CFrame = CFrame.new(base)
		root.CanCollide = true -- the biggest shell part stays solid
		root = core
	end

	local rootPart = root :: BasePart
	rootPart.Anchored = true
	for _, p in parts do
		local key = baseName(p)
		local entry = info.Parts[key]
		local look = if entry then entry.Look else "Plastic"
		applyLook(p, entry and entry.Color, look)
		if look == "Neon" or look == "Glass" then
			p.Parent = glow
		elseif p.Parent == glow then
			p.Parent = model
		end
		if p ~= rootPart then
			p.Anchored = false
			p.Massless = true
			if not (info.Kind == "Egg" and key == info.Root) then
				p.CanCollide = false
			end
			local weld = Instance.new("WeldConstraint")
			weld.Name = "CreatureWeld"
			weld.Part0 = rootPart
			weld.Part1 = p
			weld.Parent = p
		end
	end

	-- Socket markers -> Attachments on the root (markers are removed).
	for name, position in socketPositions do
		local old = rootPart:FindFirstChild(name)
		if old and old:IsA("Attachment") then
			old:Destroy()
		end
		local a = Instance.new("Attachment")
		a.Name = name
		a.Parent = rootPart
		a.WorldPosition = position
	end
	for _, s in sockets do
		s:Destroy()
	end
	if #glow:GetChildren() == 0 then
		glow:Destroy()
	end

	model:SetAttribute("Asset", asset)
	model:SetAttribute("Kind", info.Kind)
	for key, value in info.Attributes do
		model:SetAttribute(key, value)
	end
	if info.Kind == "Monster" then
		local bonus = CreatureKit.FollowerBonus(info.Rarity)
		model:SetAttribute("FollowerWalkSpeed", bonus.WalkSpeed)
		model:SetAttribute("FollowerCashBonus", bonus.CashBonus)
	end
	model.PrimaryPart = rootPart
	print(string.format("[CreatureKit] Assembled %s (%s %s, %d parts, %d sockets)",
		model.Name, info.Rarity, info.Kind, #parts, #sockets))
end

-- Assembles every creature Model directly inside container (e.g. a folder).
function CreatureKit.AssembleAll(container: Instance)
	for _, child in container:GetChildren() do
		if child:IsA("Model") and BestiaryData.Assets[child:GetAttribute("Asset") or child.Name] then
			CreatureKit.Assemble(child)
		end
	end
end

local function folder(parent: Instance, name: string): Instance
	local found = parent:FindFirstChild(name)
	if not found then
		found = Instance.new("Folder")
		found.Name = name
		found.Parent = parent
	end
	return found
end

-- What an imported model in Workspace holds: "Family" (bestiary parts),
-- "Shards" (BestiaryVFXMeshes) or nil. Goes by part names, not the model's name.
local function importKind(model: Instance): string?
	if model:GetAttribute("Asset") then
		return nil -- already assembled
	end
	for _, d in model:GetDescendants() do
		if d:IsA("BasePart") then
			local name = baseName(d)
			if string.match(name, "^EggShard%d+_") then
				return "Shards"
			end
			local asset = string.match(name, "^(%w+)_")
			if asset and BestiaryData.Assets[asset] then
				return "Family"
			end
		end
	end
	return nil
end

--[[ SetupAll() - the whole Studio setup in one call (command bar, Edit mode):
     every imported family in Workspace is unpacked and assembled; eggs go to
     Workspace.Bestiary, monsters to ServerStorage.Bestiary (the hatch
     templates), and the imported BestiaryVFXMeshes goes to
     ReplicatedStorage.VFXMeshes. Imports are recognised by their part names,
     so it doesn't matter what Studio called them. ]]
function CreatureKit.SetupAll()
	local eggs = folder(workspace, "Bestiary")
	local monsters = folder(game:GetService("ServerStorage"), "Bestiary")
	local counts = { Egg = 0, Monster = 0 }
	local shards = nil
	for _, child in workspace:GetChildren() do
		local kind = if child:IsA("Model") then importKind(child) else nil
		if kind == "Shards" then
			shards = child
		elseif kind == "Family" then
			for _, model in CreatureKit.Unpack(child) do
				CreatureKit.Assemble(model)
				local isEgg = model:GetAttribute("Kind") == "Egg"
				local destination = if isEgg then eggs else monsters
				local old = destination:FindFirstChild(model.Name)
				if old and old ~= model then
					old:Destroy()
				end
				model.Parent = destination
				counts[if isEgg then "Egg" else "Monster"] += 1
			end
		end
	end
	if shards then
		shards.Name = "BestiaryVFXMeshes"
		local meshes = folder(ReplicatedStorage, "VFXMeshes")
		local old = meshes:FindFirstChild("BestiaryVFXMeshes")
		if old then
			old:Destroy()
		end
		shards.Parent = meshes
	end
	print(string.format("[CreatureKit] SetupAll: %d eggs -> Workspace.Bestiary, %d monsters -> ServerStorage.Bestiary%s",
		counts.Egg, counts.Monster, if shards then ", shards -> ReplicatedStorage.VFXMeshes" else ""))
end


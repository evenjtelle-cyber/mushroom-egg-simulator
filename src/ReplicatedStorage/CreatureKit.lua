--[[
	CreatureKit  (ModuleScript)
	Location: ReplicatedStorage.CreatureKit

	Studio assembly and runtime effects for every egg and monster made by
	blender/GenerateBestiary.py (7 eggs, 34 monsters). All of it is driven by
	ReplicatedStorage.BestiaryData (generated by the same script), so new or
	changed creatures need no code here.

	1) ONE-TIME SETUP in Studio (Edit mode, command bar). Import each
	   Family_<Egg>.glb and BestiaryVFXMeshes.glb into Workspace, then:
	     require(game.ReplicatedStorage.CreatureKit).SetupAll()
	   which does, for each family:
	     local K = require(game.ReplicatedStorage.CreatureKit); for _, m in K.Unpack(workspace.Family_Lava) do K.Assemble(m) end
	   and sorts eggs into Workspace.Bestiary, monsters into ServerStorage.Bestiary.
	   Unpack splits the imported family into one Model per creature (named
	   after the asset, e.g. "CinderpawPup"). Assemble colours and studs it,
	   moves glowing parts into a "Glow" sub-model, welds everything to the
	   root, turns the Socket_ markers into Attachments and writes your stats
	   as attributes. Safe to run again.

	2) RUNTIME:
	     local handle = K.StartMonster(model)   -- idle (Hop / Hover / Breathe) + theme particles, more with rarity
	     local handle = K.StartEgg(eggModel)    -- rocks on the ground, theme particles, name/rarity/price label
	     handle.Stop()
	     K.PlayHatch(eggModel, function(centre) ... end)   -- wobble, flash, shards in the egg's colours
	     K.ResetEgg(eggModel)
	     local asset = K.RollHatch("Lava", luck)   -- weighted pick from the family's HatchChance
	     local bonus = K.FollowerBonus("Epic")     -- { WalkSpeed = 4, CashBonus = 0.25 }
]]

